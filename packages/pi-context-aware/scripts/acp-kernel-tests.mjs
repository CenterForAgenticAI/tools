#!/usr/bin/env node
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { repositoryCloneArgs } from "./acp-kernel-source.mjs";
import { KERNEL_TEST_COMMIT, KERNEL_TEST_VERSION, relocateTest, sha256, verifyTestFile } from "./acp-kernel-tests-source.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const destination = path.join(root, "tests/acp-kernel");
const repoUrl = "https://github.com/ranxianglei/acp-kernel.git";
const exec = (cmd, args, options = {}) => execFileSync(cmd, args, { timeout: 120_000, ...options });
const list = (dir, prefix = "") => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? list(path.join(dir, e.name), `${prefix}${e.name}/`) : [`${prefix}${e.name}`]).sort();

/** Inventory every upstream test; exclude entire files if they import an uncopied entrypoint. */
function inventory(repo) {
	const commit = exec("git", ["-C", repo, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
	if (commit !== KERNEL_TEST_COMMIT) throw new Error(`upstream commit ${commit} is not pinned ${KERNEL_TEST_COMMIT}`);
	const files = [], excluded = [];
	for (const file of list(path.join(repo, "tests"))) {
		const original = fs.readFileSync(path.join(repo, "tests", file), "utf8");
		const missing = [...original.matchAll(/(?:\bfrom\s*|\bimport\s*\(\s*)["']\.\.\/src\/([^"']+)["']/gu)].map((m) => m[1]).filter((s) => !fs.existsSync(path.join(root, "src/folds/kernel", s.replace(/\.js$/u, ".ts"))));
		if (missing.length) { excluded.push({ file, reason: `Imports uncopied entrypoint modules: ${[...new Set(missing)].join(", ")}` }); continue; }
		const relocated = relocateTest(original);
		files.push({ file, upstreamSha256: sha256(original), sha256: sha256(relocated.text), changes: relocated.changes });
	}
	return { repository: repoUrl, commit, files, excluded };
}

function check(manifest, upstream) {
	if (manifest.commit !== KERNEL_TEST_COMMIT) throw new Error("test provenance is not pinned");
	const expected = manifest.files.map((r) => r.file).sort();
	const actual = list(destination).filter((f) => !["PROVENANCE.md", "provenance.json"].includes(f));
	if (JSON.stringify(actual) !== JSON.stringify(expected)) throw new Error("vendored test inventory differs from provenance");
	for (const record of manifest.files) {
		const recovered = verifyTestFile(fs.readFileSync(path.join(destination, record.file), "utf8"), record);
		if (upstream && recovered !== fs.readFileSync(path.join(upstream, "tests", record.file), "utf8")) throw new Error(`${record.file}: differs from upstream`);
	}
	if (upstream && JSON.stringify(manifest) !== JSON.stringify(inventory(upstream))) throw new Error("upstream inventory/provenance differs");
	console.log(`Kernel test provenance OK: ${manifest.files.length} files, ${manifest.excluded.length} exclusions${upstream ? ", upstream byte comparison" : ", offline sha256 comparison"}`);
}

const [mode = "--run", suppliedRepo] = process.argv.slice(2);
if (!["--sync", "--check", "--upstream-check", "--run"].includes(mode) || (mode === "--sync" && !suppliedRepo)) throw new Error("usage: node scripts/acp-kernel-tests.mjs [--run | --check | --upstream-check [repo] | --sync <pinned repo>]");
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "acp-kernel-tests-"));
try {
	let upstream = suppliedRepo;
	if (mode === "--upstream-check" && !upstream) {
		upstream = path.join(temp, "upstream");
		exec("git", repositoryCloneArgs(repoUrl, upstream));
		exec("git", ["-C", upstream, "checkout", "--quiet", KERNEL_TEST_COMMIT]);
	}
	if (mode === "--sync") {
		const manifest = inventory(upstream);
		fs.mkdirSync(destination, { recursive: true });
		const priorFile = path.join(destination, "provenance.json");
		if (fs.existsSync(priorFile)) {
			const prior = JSON.parse(fs.readFileSync(priorFile, "utf8"));
			for (const { file } of prior.files) if (!manifest.files.some((r) => r.file === file)) fs.rmSync(path.join(destination, file));
		}
		for (const record of manifest.files) {
			const target = path.join(destination, record.file);
			fs.mkdirSync(path.dirname(target), { recursive: true });
			fs.writeFileSync(target, relocateTest(fs.readFileSync(path.join(upstream, "tests", record.file), "utf8")).text);
		}
		fs.writeFileSync(path.join(destination, "provenance.json"), `${JSON.stringify(manifest, null, 2)}\n`);
		fs.writeFileSync(path.join(destination, "PROVENANCE.md"), `# acp-kernel test provenance\n\nRepository: ${repoUrl}\nCommit: \`${KERNEL_TEST_COMMIT}\` (acp-kernel@${KERNEL_TEST_VERSION}).\n\nGenerated by \`node scripts/acp-kernel-tests.mjs --sync <pinned checkout>\`.\n\`provenance.json\` lists every copied file, upstream and local SHA-256,\nevery import-specifier replacement and occurrence count, and every exclusion.\nNo test body changes; fixture files are unchanged. Entire mixed tests importing\nwire, panel or persist modules are excluded, not edited. Tests named wire-schema\nthat only import copied engine modules are included.\n\nRun \`node scripts/acp-kernel-tests.mjs --check\` offline, or\n\`node scripts/acp-kernel-tests.mjs --upstream-check\` for independent upstream\nbyte and inventory comparison. Upstream license: ../../src/folds/kernel/PROVENANCE.md.\n`);
	}
	const manifest = JSON.parse(fs.readFileSync(path.join(destination, "provenance.json"), "utf8"));
	check(manifest, upstream);
	if (mode === "--run") {
		// Like upstream tsx, transpile without type-checking test bodies. Production TS is checked by npm run check.
		for (const [source, prefix] of [[path.join(root, "src/folds/kernel"), "src/folds/kernel"], [destination, "tests/acp-kernel"]]) {
			for (const file of list(source)) {
				if (file.endsWith(".d.ts")) continue;
				const target = path.join(temp, prefix, file.replace(/\.ts$/u, ".js"));
				fs.mkdirSync(path.dirname(target), { recursive: true });
				const text = fs.readFileSync(path.join(source, file), "utf8");
				fs.writeFileSync(target, file.endsWith(".ts") ? ts.transpileModule(text, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText : text);
			}
		}
		fs.writeFileSync(path.join(temp, "package.json"), '{"type":"module"}');
		const tests = manifest.files.filter((r) => r.file.endsWith(".test.ts")).map((r) => path.join(temp, "tests/acp-kernel", r.file.replace(/\.ts$/u, ".js")));
		exec(process.execPath, ["--test", ...tests], { stdio: "inherit", timeout: 480_000 });
	}
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
