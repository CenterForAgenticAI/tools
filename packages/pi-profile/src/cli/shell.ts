import { ENV_KEYS } from "../core/env.ts";
import type { EnvPlan } from "../core/launch.ts";
import { Refusal } from "../core/result.ts";

export const SHELLS = ["fish", "bash", "zsh"] as const;
export type Shell = (typeof SHELLS)[number];

export function isShell(v: string | undefined): v is Shell {
	return v !== undefined && (SHELLS as readonly string[]).includes(v);
}

export function quote(shell: Shell, value: string): string {
	if (shell === "fish") return `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
	return `'${value.replace(/'/g, `'\\''`)}'`;
}

const SAFE_NAME = /^[A-Z_][A-Z0-9_]*$/;

/**
 * Shell code that applies `plan`. `scope: "global"` changes the current
 * shell (`use`); `scope: "function"` is for fish `run`, where the change
 * must end with the calling function.
 */
export function envCode(shell: Shell, plan: EnvPlan, scope: "global" | "function" = "global"): string {
	const lines: string[] = [];
	for (const [name, value] of plan) {
		if (!SAFE_NAME.test(name)) throw new Refusal(`unsafe variable name: ${name}`);
		if (shell === "fish") {
			const flag = scope === "global" ? "-gx" : "-fx";
			if (value !== undefined) lines.push(`set ${flag} ${name} ${quote(shell, value)}`);
			else if (scope === "global") lines.push(`set -e ${name}`);
			else lines.push(`set -fx ${name}`);
		} else if (value !== undefined) lines.push(`export ${name}=${quote(shell, value)}`);
		else lines.push(`unset ${name}`);
	}
	return `${lines.join("\n")}\n`;
}

/** Variables a profile switch may change; used by the shell wrappers. */
export const MANAGED = ["PI_CODING_AGENT_DIR", "PI_PROFILE_LABEL", ...ENV_KEYS];

const FISH = `# pi-profile shell integration (fish). Generated by: pi-profile shell-init fish
function pi-profile --description 'Pi profiles'
    switch "$argv[1]"
        case use
            set -l code (command pi-profile env --shell fish -- $argv[2..-1]); or return $status
            printf '%s\\n' $code | source
            printf 'active profile: %s\\n' "$PI_PROFILE_LABEL"
        case run
            if test (count $argv) -lt 2
                command pi-profile help >&2
                return 2
            end
            __pi_profile_run $argv[2..-1]
        case '*'
            command pi-profile $argv
    end
end

function __pi_profile_run
    set -l code (command pi-profile env --scope function --shell fish -- $argv[1]); or return $status
    printf '%s\\n' $code | source
    if functions -q __pi_profile_pi
        __pi_profile_pi $argv[2..-1]
    else
        command pi $argv[2..-1]
    end
end

if functions -q pi; and not functions -q __pi_profile_pi
    functions -c pi __pi_profile_pi
end

function pi --wraps pi --description 'pi, with --profile NAME'
    if test (count $argv) -ge 2; and test "$argv[1]" = --profile
        __pi_profile_run $argv[2..-1]
        return $status
    end
    if test (count $argv) -ge 1; and string match -q -- '--profile=*' $argv[1]
        __pi_profile_run (string replace -- '--profile=' '' $argv[1]) $argv[2..-1]
        return $status
    end
    if functions -q __pi_profile_pi
        __pi_profile_pi $argv
    else
        command pi $argv
    end
end

if status is-interactive; and not set -q PI_PROFILE_NO_GLOBAL_DEFAULT; and not set -q PI_CODING_AGENT_DIR; and not set -q PI_PROFILE_LABEL
    command pi-profile startup --shell fish 2>/dev/null | source
end
`;

/**
 * Shell code that saves an existing pi alias or function before the wrapper
 * replaces it. It runs once: sourcing the script again keeps the first copy.
 * The alias is removed before "function pi" is parsed, or bash expands it.
 */
const PRESERVE = {
	bash: `if [ -z "\${__pi_profile_saved-}" ]; then
    __pi_profile_saved=1
    if [ -n "\${BASH_ALIASES[pi]+x}" ]; then __pi_profile_pi_alias="\${BASH_ALIASES[pi]}"; fi
    if declare -F pi >/dev/null 2>&1; then eval "__pi_profile_pi() $(declare -f pi | tail -n +2)"; fi
fi
unalias pi 2>/dev/null || true`,
	zsh: `if [ -z "\${__pi_profile_saved-}" ]; then
    __pi_profile_saved=1
    if (( \${+aliases[pi]} )); then __pi_profile_pi_alias="\${aliases[pi]}"; fi
    if (( \${+functions[pi]} )); then functions[__pi_profile_pi]="\${functions[pi]}"; fi
fi
unalias pi 2>/dev/null || true`,
} as const;

const HAS_FN = {
	bash: "declare -F __pi_profile_pi >/dev/null 2>&1",
	zsh: "(( ${+functions[__pi_profile_pi]} ))",
} as const;

const POSIX = (shell: "bash" | "zsh"): string => `# pi-profile shell integration (${shell}). Generated by: pi-profile shell-init ${shell}
pi-profile() {
    case "$1" in
        use)
            shift
            local __pp_code
            __pp_code="$(command pi-profile env --shell ${shell} -- "$@")" || return $?
            eval "$__pp_code"
            printf 'active profile: %s\\n' "$PI_PROFILE_LABEL"
            ;;
        run)
            shift
            if [ $# -lt 1 ]; then command pi-profile help >&2; return 2; fi
            __pi_profile_run "$@"
            ;;
        *)
            command pi-profile "$@"
            ;;
    esac
}

__pi_profile_run() {
    local __pp_code
    __pp_code="$(command pi-profile env --shell ${shell} -- "$1")" || return $?
    shift
    ( eval "$__pp_code"; __pi_profile_pi_call "$@" )
}

# Keep a pi function or alias defined before this script, and call it instead
# of the bare command. Inside it, "pi" means the real command.
${PRESERVE[shell]}

__pi_profile_pi_call() {
    local __pi_profile_inner=1
    if [ -n "\${__pi_profile_pi_alias-}" ]; then
        eval "$__pi_profile_pi_alias \\"\\$@\\""
    elif ${HAS_FN[shell]}; then
        __pi_profile_pi "$@"
    else
        command pi "$@"
    fi
}

function pi {
    if [ -n "\${__pi_profile_inner-}" ]; then command pi "$@"; return; fi
    case "$1" in
        --profile) shift; __pi_profile_run "$@" ;;
        --profile=*) local __pp_name="\${1#--profile=}"; shift; __pi_profile_run "$__pp_name" "$@" ;;
        *) __pi_profile_pi_call "$@" ;;
    esac
}

if [ -z "\${PI_PROFILE_NO_GLOBAL_DEFAULT+x}" ] && [ -z "\${PI_CODING_AGENT_DIR+x}" ] && [ -z "\${PI_PROFILE_LABEL+x}" ]; then
    eval "$(command pi-profile startup --shell ${shell} 2>/dev/null)"
fi
`;

/** Script for `eval`/`source` in a shell's startup file. */
export function shellInit(shell: Shell): string {
	return shell === "fish" ? FISH : POSIX(shell);
}
